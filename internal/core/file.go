// File represents an open file.
// Final will not create a File object unless a file is opened.
type File struct {
	file     *os.File
	filePath string
	isOpen   bool
}

// OpenFile opens an existing file for read-only access.
// It returns the File object and true if the file was opened successfully.
// It returns nil and false if the file was not opened successfully.
func OpenFile(filePath string) (*File, bool) {
	file, err := os.Open(filePath)
	if err != nil {
		return nil, false
	}
	return &File{
		file:     file,
		filePath: filePath,
		isOpen:   true,
	}, true
}

// CreateFile creates or truncates the named file.
// It returns the File object and true if the file was opened successfully.
// It returns nil and false if the file was not opened successfully.
func CreateFile(filePath string) (*File, bool) {
	file, err := os.Create(filePath)
	if err != nil {
		return nil, false
	}
	return &File{
		file:     file,
		filePath: filePath,
		isOpen:   true,
	}, true
}

// CreateTempFile creates a temporary file in the system's default temporary file directory.
// The filename is generated by appending a random string to pattern.
// It returns the File object and true if the file was opened successfully.
// It returns nil and false if the file was not opened successfully.
func CreateTempFile(pattern string) (*File, bool) {
	file, err := os.CreateTemp("", pattern)
	if err != nil {
		return nil, false
	}
	return &File{
		file:     file,
		filePath: "",
		isOpen:   true,
	}, true
}

// Close closes the file.
// Note that files do not have a "Flush" method.
// Flush is a Stream concept, not a File concept.
func (f *File) Close() error {
	err := f.file.Close()
	f.isOpen = false
	return err
}

func (f *File) IsOpen() bool {
	return f.isOpen
}

// FilePathExists reports whether path names an existing file or directory.
// Returns false when the path does not exist; panics on other stat errors.
func FilePathExists(path string) bool {
	_, err := os.Stat(path)
	if err == nil {
		return true
	}
	if os.IsNotExist(err) {
		return false
	}
	panic(fmt.Errorf("File.fileExists?: stat %q: %w", path, err))
}

func (f *File) FinalType() *Type {
	return GetTypeRegistrar().Get("File")
}

// FileReadBytes reads the entire contents of the named file into a ByteList.
func FileReadBytes(path string) (*ByteList, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("File.readBytes: %w", err)
	}
	return NewByteListFromBytes(data), nil
}

// FileWriteBytes creates or truncates path and writes data.
func FileWriteBytes(path string, data []byte) error {
	if err := os.WriteFile(path, data, 0o666); err != nil {
		return fmt.Errorf("File.writeBytes: %w", err)
	}
	return nil
}

// FileReadText reads the entire contents of the named file as a String.
func FileReadText(path string) (String, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", fmt.Errorf("File.readText: %w", err)
	}
	return String(data), nil
}

// FileWriteText creates or truncates path and writes the UTF-8 bytes of text.
func FileWriteText(path string, text string) error {
	return FileWriteBytes(path, []byte(text))
}

func registerFileMembers(t *Type) {
	// ( path:s -- b )
	existsFn := func(f *RunFrame, _ *TypeObjPair) {
		path := string(f.RP.DataStack.Pop().(String))
		f.RP.DataStack.Push(Bool(FilePathExists(path)))
	}
	t.registerNativeClassMethodSec("exists?", existsFn, SR_FileSystemRead)
	t.registerNativeClassMethodSec("fileExists?", existsFn, SR_FileSystemRead) // alias

	// ( path:s -- fi:FileInfo true | err:s false )
	t.registerNativeClassMethodSec("info", func(f *RunFrame, _ *TypeObjPair) {
		path := string(f.RP.DataStack.Pop().(String))
		fi, err := fileInfoFromPath(path)
		pushStreamOpenResult(f, fi, err)
	}, SR_FileSystemRead)

	// ( srcfilepath:s -- true | err:s false )
	t.registerNativeClassMethodSec("delete", func(f *RunFrame, _ *TypeObjPair) {
		path := string(f.RP.DataStack.Pop().(String))
		pushStreamWriteResult(f, fileDelete(path))
	}, SR_FileWrite)

	// ( srcfilepath:s dstfilepath:s -- true | err:s false )
	t.registerNativeClassMethodSec("move", func(f *RunFrame, _ *TypeObjPair) {
		dst := string(f.RP.DataStack.Pop().(String))
		src := string(f.RP.DataStack.Pop().(String))
		pushStreamWriteResult(f, fileMove(src, dst))
	}, SR_FileWrite)

	// ( srcfilepath:s dstdirpath:s -- true | err:s false )
	t.registerNativeClassMethodSec("copy", func(f *RunFrame, _ *TypeObjPair) {
		dstdir := string(f.RP.DataStack.Pop().(String))
		src := string(f.RP.DataStack.Pop().(String))
		pushStreamWriteResult(f, fileCopyToDir(src, dstdir))
	}, SR_FileRead|SR_FileWrite)

	// ( name:s -- base:s ext:s ) — ext without dot
	t.registerNativeClassMethod("getBaseExt", func(f *RunFrame, _ *TypeObjPair) {
		name := string(f.RP.DataStack.Pop().(String))
		base, ext := pathBaseExt(name)
		f.RP.DataStack.Push(String(base))
		f.RP.DataStack.Push(String(ext))
	})

	// ( base:s ext:s -- name:s ) — ext without dot; empty ext → base alone
	t.registerNativeClassMethod("makeName", func(f *RunFrame, _ *TypeObjPair) {
		ext := string(f.RP.DataStack.Pop().(String))
		base := string(f.RP.DataStack.Pop().(String))
		f.RP.DataStack.Push(String(fileMakeName(base, ext)))
	})

	// ( path:s -- bytes:ByteList ) — panics on error
	t.registerNativeClassMethodSec("readBytes", func(f *RunFrame, _ *TypeObjPair) {
		path := string(f.RP.DataStack.Pop().(String))
		list, err := FileReadBytes(path)
		if err != nil {
			panic(err)
		}
		f.RP.DataStack.Push(list)
	}, SR_FileRead)
	// ( path:s -- bytes:ByteList true | err:s false )
	t.registerNativeClassMethodSec("readBytes?", func(f *RunFrame, _ *TypeObjPair) {
		path := string(f.RP.DataStack.Pop().(String))
		list, err := FileReadBytes(path)
		pushStreamOpenResult(f, list, err)
	}, SR_FileRead)
	// ( path:s bytes:ByteList -- ) — panics on error
	t.registerNativeClassMethodSec("writeBytes", func(f *RunFrame, _ *TypeObjPair) {
		list := f.RP.DataStack.Pop().(*ByteList)
		path := string(f.RP.DataStack.Pop().(String))
		if err := FileWriteBytes(path, list.items); err != nil {
			panic(err)
		}
	}, SR_FileWrite)
	// ( path:s bytes:ByteList -- true | err:s false )
	t.registerNativeClassMethodSec("writeBytes?", func(f *RunFrame, _ *TypeObjPair) {
		list := f.RP.DataStack.Pop().(*ByteList)
		path := string(f.RP.DataStack.Pop().(String))
		pushStreamWriteResult(f, FileWriteBytes(path, list.items))
	}, SR_FileWrite)
	// ( path:s -- s ) — panics on error
	t.registerNativeClassMethodSec("readText", func(f *RunFrame, _ *TypeObjPair) {
		path := string(f.RP.DataStack.Pop().(String))
		s, err := FileReadText(path)
		if err != nil {
			panic(err)
		}
		f.RP.DataStack.Push(s)
	}, SR_FileRead)
	// ( path:s -- s true | err:s false )
	t.registerNativeClassMethodSec("readText?", func(f *RunFrame, _ *TypeObjPair) {
		path := string(f.RP.DataStack.Pop().(String))
		s, err := FileReadText(path)
		pushStreamOpenResult(f, s, err)
	}, SR_FileRead)
	// ( path:s s -- ) — panics on error
	t.registerNativeClassMethodSec("writeText", func(f *RunFrame, _ *TypeObjPair) {
		text := string(f.RP.DataStack.Pop().(String))
		path := string(f.RP.DataStack.Pop().(String))
		if err := FileWriteText(path, text); err != nil {
			panic(err)
		}
	}, SR_FileWrite)
	// ( path:s s -- true | err:s false )
	t.registerNativeClassMethodSec("writeText?", func(f *RunFrame, _ *TypeObjPair) {
		text := string(f.RP.DataStack.Pop().(String))
		path := string(f.RP.DataStack.Pop().(String))
		pushStreamWriteResult(f, FileWriteText(path, text))
	}, SR_FileWrite)
}

// fileDelete removes a file or empty directory (os.Remove). Non-empty dir → error.
func fileDelete(path string) error {
	if err := os.Remove(path); err != nil {
		return fmt.Errorf("File.delete: %w", err)
	}
	return nil
}

// fileMove renames/relocates src to dst (full destination path). Fails if dst exists.
func fileMove(src, dst string) error {
	if FilePathExists(dst) {
		return fmt.Errorf("File.move: destination %q already exists", dst)
	}
	if err := os.Rename(src, dst); err != nil {
		return fmt.Errorf("File.move: %w", err)
	}
	return nil
}

// fileCopyToDir copies src file into dstdir as filepath.Base(src). Does not create dstdir.
// Fails if destination file already exists.
func fileCopyToDir(src, dstdir string) error {
	info, err := os.Stat(dstdir)
	if err != nil {
		return fmt.Errorf("File.copy: dest dir: %w", err)
	}
	if !info.IsDir() {
		return fmt.Errorf("File.copy: %q is not a directory", dstdir)
	}
	dst := filepath.Join(dstdir, filepath.Base(src))
	if FilePathExists(dst) {
		return fmt.Errorf("File.copy: destination %q already exists", dst)
	}
	in, err := os.Open(src)
	if err != nil {
		return fmt.Errorf("File.copy: open src: %w", err)
	}
	defer in.Close()
	out, err := os.OpenFile(dst, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o666)
	if err != nil {
		return fmt.Errorf("File.copy: create dest: %w", err)
	}
	defer out.Close()
	if _, err := io.Copy(out, in); err != nil {
		_ = os.Remove(dst)
		return fmt.Errorf("File.copy: %w", err)
	}
	return nil
}

func fileMakeName(base, ext string) string {
	ext = strings.TrimPrefix(ext, ".")
	if ext == "" {
		return base
	}
	return base + "." + ext
}

